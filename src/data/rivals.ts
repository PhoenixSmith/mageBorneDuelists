import type { RivalMage, Mage } from '../types';

function makeMage(
  id: string,
  name: string,
  origin: Mage['origin'],
  mastery: Mage['mastery'],
  deck: string[],
  coin: number,
  reputation: number,
): Mage {
  return {
    id,
    name,
    origin,
    vitality: 10,
    maxVitality: 10,
    focus: 4,
    maxFocus: 4,
    guard: 0,
    resolve: 10,
    maxResolve: 10,
    mastery,
    manaPool: { fire: 0, water: 0, wind: 0, earth: 0 },
    attunementUsed: false,
    grimoire: deck,
    preparedDeck: deck,
    hand: [],
    discard: [],
    burned: [],
    fatigueCount: 0,
    range: 'near',
    conditions: [],
    equipment: { trinkets: [], consumables: [] },
    coin,
    reagents: {},
    reputation,
    notoriety: 0,
    titles: [],
    injuries: [],
  };
}

